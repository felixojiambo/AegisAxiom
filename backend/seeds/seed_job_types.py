async def seed_job_types():
    client = AsyncIOMotorClient(os.environ.get("MONGO_URL", "mongodb://localhost:27017"))
    db = client[os.environ.get("DB_NAME", "test_database")]

    for jt in JOB_TYPES:
        jt["created_at"] = datetime.now(timezone.utc)
        jt["updated_at"] = datetime.now(timezone.utc)
        await db.job_types.update_one(
            {"type_id": jt["type_id"]},
            {"$set": jt},
            upsert=True
        )
        print(f"  Seeded: {jt['name']} ({len(jt['checkin'])} check-in, {len(jt['checkout'])} check-out items)")

    print(f"\n  {len(JOB_TYPES)} job types seeded.")


if __name__ == "__main__":
    asyncio.run(seed_job_types())
